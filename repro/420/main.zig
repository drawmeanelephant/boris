//! Standalone reproducer for drawmeanelephant/boris#420:
//! "Touch Atlas streaming checks parse is byte-offset sensitive: identical
//! 216-finding report passes at one file length, fails at finding #207 at
//! another."
//!
//! Mechanism (root cause):
//!   `writeAfterClaims` streams the committed checks report through
//!   `EvidenceInput.pass2_buffer` — a fixed 64 KiB chunk — and hands the
//!   stream to `std.json.Reader`. When a JSON string VALUE straddles a 64 KiB
//!   chunk boundary, the scanner cannot complete the token and surfaces it as
//!   a `.partial_string` token. `skipJsonValue` in src/publication_touches.zig
//!   (boris @ 30805ab8) treats that partial token as a complete value and
//!   returns, leaving the scanner mid-string. The next key read then consumes
//!   the remainder of the string as a key token, which fails the finding
//!   schema -> `error.InvalidChecksReport`.
//!
//!   Whether any token straddles a boundary is a pure function of the file's
//!   byte length, which is why a 218-byte-shorter report (the "public" target
//!   form) fails while the identical content under the "default" target
//!   parses cleanly (boris#417). Inside an object-skip, `.partial_string`
//!   tokens are harmless (the depth loop just reads the next token), which is
//!   why only bare-string values skipped via `skipJsonValue` — e.g. a
//!   finding's `owner` — trigger it.
//!
//! This harness synthesizes a schema-valid 216-finding checks report, pads it
//! so that finding #207's `"owner":"publication"` value straddles the 64 KiB
//! boundary, and drives the REAL `parseChecksStream` through the same 64 KiB
//! streaming reader `writeAfterClaims` uses. The identical report padded by
//! exactly 13 bytes more (no straddle) parses all 216 findings.

const std = @import("std");
const builtin = @import("builtin");
const publication_touches = @import("publication_touches");

const Io = std.Io;

const expected_target = "public";
const finding_count = 216;
const finding_index = 207; // 0-based: the 208th finding
const boundary_bytes = 64 * 1024;
const work_subdir = "repro-420-io";
const checks_file = "repro-420-io/checks.json";

// Preamble of the committed checks report (format / schema_version / target /
// artifact_inventory / checks[3]) generated by boris 30805ab8 itself. Its
// checks record finding counts [0, 0, 216], so the schema-validating tail of
// parseChecksStream (finding_offset chaining + last_end == findings.len)
// agrees exactly with the 216 findings generated below. Bytes 0..2241 of the
// real checks.json — the `"findings": [` opener is included.
const preamble =
    "{\n  \"format\": \"boris-publication-checks\",\n  \"schema_version\": 1,\n  \"target\": \"public\",\n  \"artifact_inventory\": {\n    \"path\": \"_boris/proof/artifacts.json\",\n    \"bytes\": 11840,\n    \"sha256\": \"ac5ef4252a00b30b0f06cee65d07c24c171ef3117389a6151dde208dc78194f3\",\n    \"format\": \"boris-publication-artifacts\",\n    \"schema_version\": 1,\n    \"target\": \"public\",\n    \"artifact_count\": 39\n  },\n  \"checks\": [\n    {\n      \"id\": \"artifact-integrity\",\n      \"eligible\": true,\n      \"ran\": true,\n      \"status\": \"passed\",\n      \"coverage\": \"complete\",\n      \"scope\": {\n        \"subject_statuses\": [\"committed\"],\n        \"subject_kinds\": [],\n        \"subject_sha256\": \"68a3191bdc5ae6ebb4931e2108efa916721edf61225d3559a679066cff1276b2\",\n        \"supporting_statuses\": [],\n        \"supporting_kinds\": [],\n        \"supporting_sha256\": \"e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855\"\n      },\n      \"counts\": {\"eligible\": 39, \"checked\": 39, \"findings\": 0},\n      \"finding_offset\": 0\n    },\n    {\n      \"id\": \"rendered-html\",\n      \"eligible\": true,\n      \"ran\": true,\n      \"status\": \"passed\",\n      \"coverage\": \"complete\",\n      \"scope\": {\n        \"subject_statuses\": [\"committed\"],\n        \"subject_kinds\": [\"html-page\"],\n        \"subject_sha256\": \"a427ccd6e427b14cb183ed61da84b0471aa9f37d1dba53e5533bf632ed67d10e\",\n        \"supporting_statuses\": [\"committed\"],\n        \"supporting_kinds\": [],\n        \"supporting_sha256\": \"68a3191bdc5ae6ebb4931e2108efa916721edf61225d3559a679066cff1276b2\"\n      },\n      \"counts\": {\"eligible\": 36, \"checked\": 36, \"findings\": 0},\n      \"finding_offset\": 0\n    },\n    {\n      \"id\": \"rendered-search\",\n      \"eligible\": true,\n      \"ran\": true,\n      \"status\": \"failed\",\n      \"coverage\": \"complete\",\n      \"scope\": {\n        \"subject_statuses\": [\"committed