pub fn main(init: std.process.Init) !void {
    const io = init.io;
    var arena = std.heap.ArenaAllocator.init(std.heap.page_allocator);
    defer arena.deinit();
    const gpa = arena.allocator();

    std.debug.print("repro-420: Touch Atlas streaming checks parse (boris checked-out src, zig {s})\n", .{builtin.zig_version_string});
    std.debug.print("  generating a schema-valid {d}-finding checks report; expected target {s}\n", .{ finding_count, expected_target });

    // 1) Un-padded report: locate finding #207's `"owner":"publication"` value.
    const base = try buildReport(gpa, 0);
    const owner_key_off = nthOccurrence(base, "\"owner\":\"publication\"", finding_index);
    const owner_val_off = owner_key_off + "\"owner\":".len;
    std.debug.print("  un-padded: finding #{d} owner value token at byte {d} (mod 65536 = {d})\n", .{ finding_index, owner_val_off, owner_val_off % boundary_bytes });
    if (owner_val_off >= boundary_bytes - 14 or owner_val_off < boundary_bytes - 65536)
        return error.UnsuitableLayout;

    // 2) Padding: fail case puts the 64 KiB boundary 6 bytes into the owner
    //    token (which is 13 bytes: quote + "publication" + quote); the control
    //    is the same report 13 bytes longer, so the token sits entirely above
    //    the boundary.
    const pad_fail = boundary_bytes - owner_val_off - 6;
    const pad_pass = pad_fail + 13;
    const report_fail = try buildReport(gpa, pad_fail);
    const report_pass = try buildReport(gpa, pad_pass);

    std.debug.print("  padding: {d} bytes (failing) / {d} bytes (control)\n", .{ pad_fail, pad_pass });
    std.debug.print("  FAILING report: {d} bytes; owner token spans {d}..{d} -> straddles {d}\n", .{ report_fail.len, owner_val_off + pad_fail, owner_val_off + pad_fail + 13, boundary_bytes });
    std.debug.print("  CONTROL report: {d} bytes; owner token spans {d}..{d} -> no straddle\n", .{ report_pass.len, owner_val_off + pad_pass, owner_val_off + pad_pass + 13 });

    Io.Dir.cwd().createDirPath(io, work_subdir) catch |err| {
        std.debug.print("  !! cannot create temp dir: {s}\n", .{@errorName(err)});
        return err;
    };
    defer Io.Dir.cwd().deleteTree(io, work_subdir) catch {};

    // 3) The failing case: expect parseChecksStream to die.
    const fail_result: ?usize = runParse(io, gpa, report_fail, "failing") catch |err| switch (err) {
        error.ParseFailed => blk: {
            std.debug.print("  => REPRODUCED: parseChecksStream returned error.InvalidChecksReport on the {d}-byte report\n", .{report_fail.len});
            std.debug.print("     (finding #{d}'s skipped `owner` value straddles the 64 KiB chunk boundary)\n", .{finding_index});
            break :blk null;
        },
        else => return err,
    };

    // 4) The control: the same content, 13 bytes longer, must parse everything.
    const parsed_count = try runParse(io, gpa, report_pass, "control");
    if (parsed_count != finding_count) {
        std.debug.print("  !! control parsed {d} findings, expected {d}\n", .{ parsed_count, finding_count });
        return error.ReproFailed;
    }

    if (fail_result != null) {
        std.debug.print("  !! failing report parsed cleanly — repro did NOT reproduce\n", .{});
        return error.ReproFailed;
    }

    std.debug.print("\nRESULT: REPRODUCED — a {d}-byte checks report dies at finding #{d};\n", .{ report_fail.len, finding_index });
    std.debug.print("        the identical report at {d} bytes parses all {d} findings.\n", .{ report_pass.len, finding_count });
}

fn buildReport(gpa: std.mem.Allocator, pad: usize) ![]u8 {
    var out = std.ArrayList(u8).empty;
    errdefer out.deinit(gpa);
    try out.appendNTimes(gpa, ' ', pad);
    try out.appendSlice(gpa, preamble);
    for (0..finding_count) |i| {
        if (i != 0) try out.appendSlice(gpa, ",\n    ");
        try appendFinding(gpa, &out, i);
    }
    try out.appendSlice(gpa, "\n  ]\n}\n");
    return out.toOwnedSlice(gpa);
}

fn appendFinding(gpa: std.mem.Allocator, out: *std.ArrayList(u8), index: usize) !void {
    try out.appendSlice(gpa, "{\"code\":\"SEARCH_CONTENT_MISMATCH\",\"domain\":\"artifact\",\"severity\":\"error\",\"confidence\":\"certain\",\"owner\":\"publication\",\"subject\":{\"kind\":\"artifact\",\"id\":\"docs/page-");
    var id_buf: [64]u8 = undefined;
    const id = try std.fmt.bufPrint(&id_buf, "{d:0>3}", .{index});
    try out.appendSlice(gpa, id);
    try out.appendSlice(gpa, ".md\",\"target\":\"public\"},\"remediation\":\"");
    try out.appendNTimes(gpa, 'R', 56);
    try out.appendSlice(gpa, "\",\"fixability\":\"regenerate\"}");
}

/// Run the REAL parseChecksStream over `bytes`, streamed through a 64 KiB
/// reader exactly as writeAfterClaims does for the checks report.
fn runParse(io: Io, gpa: std.mem.Allocator, bytes: []const u8, label: []const u8) !usize {
    Io.Dir.cwd().writeFile(io, .{ .sub_path = checks_file, .data = bytes }) catch |err| {
        std.debug.print("  !! cannot write {s}: {s}\n", .{ checks_file, @errorName(err) });
        return err;
    };

    const file = try Io.Dir.cwd().openFile(io, checks_file, .{});
    defer file.close(io);
    var buffer: [boundary_bytes]u8 = undefined;
    var stream = file.readerStreaming(io, &buffer);

    const parsed = publication_touches.parseChecksStream(gpa, &stream.interface, expected_target) catch |err| {
        std.debug.print("  [{s}] parseChecksStream FAILED: {s}\n", .{ label, @errorName(err) });
        if (@errorReturnTrace()) |trace| std.debug.dumpErrorReturnTrace(trace);
        return error.ParseFailed;
    };
    std.debug.print("  [{s}] parseChecksStream parsed {d} findings\n", .{ label, parsed.findings.len });
    return parsed.findings.len;
}

fn nthOccurrence(haystack: []const u8, needle: []const u8, n: usize) usize {
    var idx: usize = 0;
    var seen: usize = 0;
    while (std.mem.indexOfPos(u8, haystack, idx, needle)) |pos| {
        if (seen == n) return pos;
        seen += 1;
        idx = pos + needle.len;
    }
    unreachable;
}
