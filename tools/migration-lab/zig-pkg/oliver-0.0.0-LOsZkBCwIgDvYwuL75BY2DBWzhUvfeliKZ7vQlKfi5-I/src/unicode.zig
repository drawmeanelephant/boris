/// The full case fold of a code point: at most three code points (the
/// longest folds are three characters, e.g. U+0390). Identity folds return
/// the input unchanged.
pub const Fold = struct {
    chars: [3]u21 = .{ 0, 0, 0 },
    len: u8 = 1,
};

/// Full Unicode case fold (binary search over the generated table).
pub fn caseFold(cp: u21) Fold {
    var lo: usize = 0;
    var hi: usize = casefold_entries.len / 5;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        const e = casefold_entries[mid * 5];
        if (e < cp) {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    if (lo < casefold_entries.len / 5 and casefold_entries[lo * 5] == cp) {
        const n: u8 = @intCast(casefold_entries[lo * 5 + 1]);
        return .{
            .chars = .{
                casefold_entries[lo * 5 + 2],
                casefold_entries[lo * 5 + 3],
                casefold_entries[lo * 5 + 4],
            },
            .len = n,
        };
    }
    return .{ .chars = .{ cp, 0, 0 }, .len = 1 };
}

fn inRanges(cp: u21, ranges: []const u21) bool {
    // Find the last range whose start is <= cp, then test its end.
    var lo: usize = 0;
    var hi: usize = ranges.len / 2;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        if (ranges[mid * 2] <= cp) {
            lo = mid + 1;
        } else {
            hi = mid;
        }
    }
    if (lo == 0) return false;
    return ranges[(lo - 1) * 2 + 1] >= cp;
}

/// True if `cp` is Unicode whitespace (spec §2.1: Zs, or tab/LF/FF/CR).
pub fn isWhitespace(cp: u21) bool {
    return inRanges(cp, &whitespace_ranges);
}

/// True if `cp` is Unicode punctuation (spec §2.1: P or S categories).
pub fn isPunctuation(cp: u21) bool {
    return inRanges(cp, &punctuation_ranges);
}

/// True if `cp` is a P-category punctuation character (Pc/Pd/Pe/Pf/Pi/Po/Ps)
/// only — symbols (S categories) are excluded. The Cooklang EBNF defines a
/// word boundary as "punctuation character = ? Unicode General Category P*
/// ?", and the Cooklang canonical corpus requires symbols like `🧂` (So) to
/// stay inside single-word names, so the Cooklang frontend uses this
/// predicate, not `isPunctuation`.
pub fn isPunctuationP(cp: u21) bool {
    return inRanges(cp, &punctuation_p_ranges);
}

test "unicode: isPunctuationP excludes symbols" {
    // P-only classification, exercised by the Cooklang canonical corpus:
    // `,` (Po) and `{` (Ps) are boundaries; `🧂` (So) and `×` (Sm) stay in
    // word runs; U+2009 is whitespace, not punctuation.
    try testing.expect(isPunctuationP(0x2C));
    try testing.expect(isPunctuationP(0x2E2B)); // ⸫ Po
    try testing.expect(isPunctuationP(0x7B));
    try testing.expect(!isPunctuationP(0x1F9C2)); // 🧂 So
    try testing.expect(!isPunctuationP(0xD7)); // × Sm
